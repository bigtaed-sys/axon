import { execFileSync } from 'node:child_process';

/**
 * Версия сборки — из git-тега, а не из package.json.
 *
 * Файл с версией, который правят руками, рано или поздно расходится с тем, что
 * на самом деле собрано: правку забыли, а сборку выпустили. Тег забыть нельзя —
 * без него версия честно скажет, что это не релиз.
 *
 * Схема календарная: `v2026.8.23` — год, месяц, число. Ведущих нулей нет
 * намеренно: npm разбирает версии по грамматике semver, а она их запрещает, и
 * `2026.08.23` не опубликуется вовсе.
 *
 * Между тегами `git describe` даёт `v2026.8.23-4-g1a2b3c` — четвёртый коммит
 * после тега. Такую версию видно невооружённым глазом: это не релиз, а сборка
 * из середины работы. Для сравнения версий такую запись разбирает
 * `parseVersion` в протоколе — по правилам semver «-4» означало бы предрелиз,
 * то есть версию *старше* тега, а на деле она новее.
 */
export function resolveVersion(fallback = '0.0.0-dev') {
  try {
    const described = execFileSync(
      'git',
      ['describe', '--tags', '--match', 'v[0-9]*', '--always', '--dirty'],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] },
    ).trim();

    if (!described) return fallback;

    // Тегов ещё нет — describe отдаёт голый хэш. Версией это называть нельзя.
    if (!described.startsWith('v')) return `${fallback}+${described}`;

    return described.slice(1);
  } catch {
    // Ни git, ни репозитория: сборка из распакованного архива. Это законный
    // случай, падать из-за него нельзя.
    return fallback;
  }
}

/** Когда собрано. В номер версии не входит, но в «О программе» полезнее её. */
export function buildStamp() {
  return new Date().toISOString();
}
