/**
 * Минимальный плагин Axon, показывающий все точки расширения.
 *
 * Обычный JavaScript: без сборки, без зависимостей, без импортов из @axon/*.
 * Всё, что нужно, приезжает аргументом `api`.
 *
 * Поставить: axon plugin link ./examples/hello-plugin
 */

export async function activate(api) {
  api.log.info('плагин просыпается', { city: api.settings.get('city') });

  // ─── Инструмент ───────────────────────────────────────────────────────────
  await api.tools.register({
    name: 'greet',
    title: 'Поздороваться',
    description:
      'Поздороваться с человеком по имени. Вызывай, когда пользователь просит ' +
      'поприветствовать кого-то или проверить, что плагин работает.',
    tier: 'safe',
    parameters: {
      type: 'object',
      properties: {
        name: { type: 'string', description: 'Кого приветствовать' },
      },
      required: ['name'],
    },
    async execute({ name }) {
      return `Привет, ${name}! Пишу из ${api.settings.get('city')}.`;
    },
  });

  // Инструмент, который нужен редко: схему в контекст сразу не грузим.
  await api.tools.register({
    name: 'ping',
    title: 'Проверить связь',
    description: 'Убедиться, что процесс плагина жив. Вызывай только по прямой просьбе.',
    tier: 'safe',
    deferred: true,
    parameters: { type: 'object', properties: {} },
    async execute(_args, ctx) {
      // Разрешение можно спросить и посреди выполнения — например, когда
      // выяснилось, что действие затронет больше, чем предполагалось.
      const granted = await ctx.requestPermission('Просто проверяю, что спрашивать умею');
      return granted ? 'жив, разрешение получено' : 'жив, разрешения не дали';
    },
  });

  // ─── Вклад в промпт ───────────────────────────────────────────────────────
  // `stable` — в кэшируемый префикс. Город меняется раз в жизни, поэтому
  // здесь это уместно. Будь тут время или погода — было бы `volatile`.
  await api.context.contribute('город', 'stable', () => {
    const city = api.settings.get('city');
    return city ? `Пользователь находится в городе ${city}.` : null;
  });

  // ─── Реакция на смену настроек ────────────────────────────────────────────
  api.settings.onChange((values) => {
    api.log.info('настройки поменялись', values);
  });

  // ─── Задача по расписанию ─────────────────────────────────────────────────
  // Расписание объявлено в манифесте, ядро зовёт этот обработчик.
  api.jobs.on('пульс', async () => {
    if (api.settings.get('verbose')) api.log.info('плагин на месте');
  });
}

export function deactivate() {
  // Снимать регистрации не нужно: ядро само убирает всё, что плагин принёс.
  // Сюда стоит класть только то, что живёт снаружи, — закрыть соединение,
  // дописать файл.
}
