import { z } from 'zod';

/** Версия протокола. Ядро и клиент обязаны совпасть по major, иначе рукопожатие отклоняется. */
export const PROTOCOL_VERSION = 1;

/**
 * Ревизия контракта: растёт, когда в него что-то добавили, не сломав старое.
 *
 * Нужна потому, что ядро в Axon — отдельная программа, и оно совершенно
 * законно может оказаться старше приложения: человек обновил десктоп, а ядро
 * на сервере осталось прежним. Ломающего изменения тут нет, `PROTOCOL_VERSION`
 * прежний, и рукопожатие проходит — но новых полей в ответах не будет.
 *
 * Ревизия не влияет на работу: читать ответы старого ядра клиент обязан
 * терпимо в любом случае. Она нужна ровно затем, чтобы вместо загадочно
 * неполного интерфейса человеку сказали словами: обнови ядро.
 *
 * Поднимать при каждом расширении контракта — новой команде, новом поле в
 * ответе, новом типе события.
 */
export const PROTOCOL_REVISION = 7;

/** Единственный формат времени на проводе — ISO-8601 в UTC. Никаких unix-миллисекунд вперемешку. */
export const zTimestamp = z.string().datetime();
export type Timestamp = z.infer<typeof zTimestamp>;

/** Идентификатор, который выдаёт ядро. Всегда UUID. */
export const zId = z.string().uuid();
export type Id = z.infer<typeof zId>;

/**
 * Идентификатор, пришедший извне — id вызова инструмента от провайдера
 * (`call_abc123` у OpenAI, `toolu_...` у Anthropic). UUID тут не гарантирован,
 * поэтому валидируем только как непустую строку.
 */
export const zExternalId = z.string().min(1).max(256);
export type ExternalId = z.infer<typeof zExternalId>;

/**
 * Номер записи в журнале ядра. Счётчик один на всё ядро, а не на разговор:
 * клиенту тогда достаточно одного курсора, чтобы догнать любое состояние
 * после переподключения. Разбор по разговорам — это индекс в БД, не второй счётчик.
 */
export const zSeq = z.number().int().nonnegative();
export type Seq = z.infer<typeof zSeq>;

/** Позиция клиента в журнале: последний seq, который он подтвердил. 0 — «я новый, дай всё». */
export const zCursor = zSeq;
export type Cursor = z.infer<typeof zCursor>;
