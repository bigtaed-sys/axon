import { z } from 'zod';

/**
 * Личность агента.
 *
 * До этого «личностью» было одно поле свободного текста — и оно по умолчанию
 * пустовало, то есть агент выходил к человеку вообще без представления о том,
 * кто он. Свободное поле выглядит гибким, но на деле перекладывает работу на
 * пользователя: написать себе хороший системный промпт умеет один из ста, а
 * остальные девяносто девять получают безликую справочную.
 *
 * Поэтому личность здесь — структура, а не блоб:
 *
 * - её можно собрать пресетами, ничего не сочиняя;
 * - ядро само превращает её в текст, одинаково для всех каналов, так что
 *   телеграм и десктоп разговаривают одним голосом, а не двумя разными;
 * - видно, из чего сложился системный блок, — это уходит в отчёт о контексте.
 *
 * Свободный текст никуда не делся, он лежит поверх (`custom`). Но теперь это
 * дополнение к характеру, а не единственный способ его задать.
 */

/** Базовый характер. `custom` — никакого готового, только собственный текст. */
export const zPersonaPreset = z.enum(['calm', 'warm', 'blunt', 'custom']);
export type PersonaPreset = z.infer<typeof zPersonaPreset>;

export const zPersona = z.object({
  /**
   * Как зовут агента. Пусто — имени ещё нет.
   *
   * Умолчания здесь нет намеренно. Подставь любое, даже название программы, —
   * и агент представится им в первом же разговоре, то есть ответит на вопрос
   * «как тебя зовут» раньше, чем человек успел на него ответить. Пустая
   * строка — это не «забыли заполнить», а честное «пока никак».
   */
  name: z.string().max(40).default(''),

  preset: zPersonaPreset.default('calm'),

  /** Как зовут человека. Пусто — агент не выдумывает обращение. */
  userName: z.string().max(40).default(''),

  /** На «ты» или на «вы». Влияет и на глаголы, поэтому это не косметика. */
  address: z.enum(['ты', 'вы']).default('ты'),

  /**
   * Юмор отдельной ручкой, а не частью характера: спокойный человек бывает и
   * с иронией, и без неё, а вот выкрутить это в пресете невозможно — пресетов
   * стало бы вдвое больше.
   */
  humor: z.enum(['none', 'dry', 'playful']).default('dry'),

  /** Длина ответа по умолчанию. */
  verbosity: z.enum(['short', 'normal', 'detailed']).default('normal'),

  /**
   * Насколько агент лезет со своим мнением и следующим шагом внутри разговора.
   * Это не про то, пишет ли он первым, — за это отвечает планировщик.
   */
  initiative: z.enum(['low', 'normal', 'high']).default('normal'),

  emoji: z.boolean().default(false),

  /** Свободное дополнение поверх собранного характера. */
  custom: z.string().max(4000).default(''),

  /**
   * Знакомство состоялось.
   *
   * Пока флага нет, агент получает задание познакомиться — узнать, как
   * обращаться к человеку и как его называть самого. Хранить это флагом, а не
   * выводить из «имя не пустое», важно: человек мог сознательно оставить
   * умолчания, и переспрашивать его об этом каждый разговор — худшее, что
   * можно сделать со знакомством.
   */
  configured: z.boolean().default(false),
});
export type Persona = z.infer<typeof zPersona>;

/** Ключ в настройках, под которым живёт поле персоны. */
export function personaKey(field: keyof Persona): string {
  return `persona.${field}`;
}

/**
 * Собрать персону из плоских настроек.
 *
 * Настройки — свободный словарь, и полей персоны там может не быть вовсе:
 * у нового ядра их нет ни одного. Поэтому разбор терпимый — каждое поле
 * падает на своё умолчание по отдельности, и одна кривая запись не обнуляет
 * характер целиком.
 */
export function readPersona(values: Record<string, unknown>): Persona {
  const raw: Record<string, unknown> = {};
  for (const field of Object.keys(zPersona.shape) as Array<keyof Persona>) {
    const value = values[personaKey(field)];
    if (value !== undefined && value !== null) raw[field] = value;
  }

  const parsed = zPersona.safeParse(raw);
  if (parsed.success) return parsed.data;

  // Поле за полем: битое отбрасываем, целое сохраняем.
  const safe: Record<string, unknown> = {};
  for (const [field, schema] of Object.entries(zPersona.shape)) {
    const one = schema.safeParse(raw[field]);
    if (one.success) safe[field] = one.data;
  }
  return zPersona.parse(safe);
}

/** Разложить персону обратно в плоские настройки. */
export function personaValues(persona: Persona): Record<string, unknown> {
  const values: Record<string, unknown> = {};
  for (const [field, value] of Object.entries(persona)) {
    values[`persona.${field}`] = value;
  }
  return values;
}

