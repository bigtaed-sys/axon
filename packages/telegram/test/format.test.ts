import { describe, expect, it } from 'vitest';
import { split, toTelegramHtml } from '../src/format.js';
import { pickBody, plain, stripTags } from '../src/TelegramAdapter.js';

describe('разметка для телеграма', () => {
  it('переводит жирный, курсив и ссылки', () => {
    expect(toTelegramHtml('**важно** и *не очень*')).toBe('<b>важно</b> и <i>не очень</i>');
    expect(toTelegramHtml('[сюда](https://axon.dev)')).toBe(
      '<a href="https://axon.dev">сюда</a>',
    );
  });

  it('заголовки и списки не теряются, а беднеют', () => {
    // В телеграме нет ни того, ни другого. Выбросить структуру хуже, чем
    // показать её беднее: человек читает не разметку, а смысл.
    expect(toTelegramHtml('## Итог')).toBe('<b>Итог</b>');
    expect(toTelegramHtml('- первое\n- второе')).toBe('• первое\n• второе');
    expect(toTelegramHtml('1. раз\n2. два')).toBe('1. раз\n2. два');
  });

  it('экранирует угловые скобки, чтобы телеграм не принял их за теги', () => {
    expect(toTelegramHtml('если a < b и b > c')).toBe('если a &lt; b и b &gt; c');
  });

  it('не размечает то, что внутри кода', () => {
    // Звёздочки в примере кода — часть примера, а не разметка. Разбери их как
    // разметку, и человек получит код, который не работает.
    const html = toTelegramHtml('в коде `a ** b` звёздочки остаются');
    expect(html).toBe('в коде <code>a ** b</code> звёздочки остаются');
  });

  it('номер в тексте не путается с заглушкой кода', () => {
    // Заглушки нумерованные, и если бы они выглядели как « 1 », то строка
    // «шаг 1 готов» подставила бы на месте единицы чужой кусок кода.
    expect(toTelegramHtml('`код` и шаг 0 готов')).toBe('<code>код</code> и шаг 0 готов');
  });

  it('блок кода сохраняет язык', () => {
    expect(toTelegramHtml('```ts\nconst a = 1;\n```')).toBe(
      '<pre><code class="language-ts">const a = 1;</code></pre>',
    );
  });

  it('закрывает блок кода, оборванный на полуслове', () => {
    // Ответ мог упереться в потолок токенов. Незакрытый тег телеграм отвергает
    // целиком — то есть человек не увидит вообще ничего.
    expect(toTelegramHtml('```\nнедописанное')).toBe('<pre>недописанное</pre>');
  });
});

describe('разрезание длинных ответов', () => {
  it('короткое не трогает', () => {
    expect(split('привет')).toEqual(['привет']);
  });

  it('режет по границе абзаца, а не посреди строки', () => {
    const text = `${'а'.repeat(80)}\n\n${'б'.repeat(80)}`;
    const parts = split(text, 100);

    expect(parts).toHaveLength(2);
    expect(parts[0]).toBe('а'.repeat(80));
    expect(parts[1]).toBe('б'.repeat(80));
  });

  it('не оставляет незакрытый блок кода на границе', () => {
    const html = `<pre>${'x'.repeat(200)}</pre>`;
    const parts = split(html, 100);

    // Обе половины должны быть самостоятельными: телеграм разбирает каждое
    // сообщение отдельно и на незакрытом теге отказывает.
    expect(parts[0]?.endsWith('</pre>')).toBe(true);
  });

  it('слишком длинный кусок без границ всё равно режется', () => {
    const parts = split('я'.repeat(250), 100);
    expect(parts.length).toBeGreaterThan(1);
    expect(parts.join('').length).toBe(250);
  });
});

describe('итог прогона', () => {
  it('ответ показывается как есть', () => {
    expect(pickBody('готово', 'end_turn')).toBe('готово');
  });

  it('пустой ответ при обычном завершении — это молчание, а не ошибка', () => {
    // Агент мог ответить одним вызовом инструмента без текста. Показывать
    // «прогон остановлен: end_turn» человеку незачем, это не про него.
    expect(pickBody('', 'end_turn')).toBe('');
  });

  it('отказ объясняется, а не проглатывается', () => {
    expect(pickBody('', 'budget_exhausted')).toContain('budget_exhausted');
    expect(pickBody('', 'error', 'сеть отвалилась')).toContain('сеть отвалилась');
  });

  it('текст важнее причины остановки', () => {
    // Успел сказать до того, как упёрся в потолок, — показываем сказанное.
    expect(pickBody('половина ответа', 'budget_exhausted')).toBe('половина ответа');
  });
});

describe('черновик', () => {
  it('показывается без разметки', () => {
    // Посреди генерации разметка почти всегда рваная: незакрытый тег —
    // и телеграм отвергает правку целиком, черновик застывает.
    expect(plain('**жирный** и `код`')).toBe('жирный и код');
  });
});

describe('запасной путь без разметки', () => {
  it('возвращает читаемый текст, когда телеграм отверг HTML', () => {
    expect(stripTags('<b>важно</b>: a &lt; b')).toBe('важно: a < b');
  });
});
