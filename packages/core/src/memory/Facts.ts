import type { Fact } from '@axon/protocol';

/**
 * Какие факты класть в промпт.
 *
 * Раньше клались все и всегда, отсортированные по алфавиту. Пока фактов
 * двадцать, это незаметно; на двухстах человек начинает платить за список
 * городов и часовых поясов в каждом ходу, включая «привет». Наблюдения
 * отбираются по весу с самого начала — факты почему-то нет.
 *
 * Отбор устроен нарочно грубо и без обращения к модели: сравнение слов вопроса
 * со словами факта. Умнее было бы эмбеддингами, но это ещё одна модель, ещё
 * один индекс и ещё одна статья расхода ради задачи, где хватает совпадения по
 * словам: человек, спрашивая про работу, произносит те же слова, которыми
 * работа записана.
 *
 * Главное правило: **сказанное человеком не выцветает**. Факт с `origin: user`
 * он сообщил сам и вправе ожидать, что агент это помнит, — такие идут в промпт
 * всегда, сколько бы их ни было. Отбор касается только выведенных агентом.
 */

/** Сколько выведенных фактов брать сверх сказанных человеком. */
const INFERRED_LIMIT = 12;

/** Ниже этого совпадение считается случайным. */
const MIN_SCORE = 1;

/** Слова короче не несут смысла: предлоги, союзы, обрывки. */
const MIN_WORD = 3;

/** Сколько первых букв слова считать основой. */
const STEM = 4;

export function selectFacts(
  facts: readonly Fact[],
  userText: string,
  limit = INFERRED_LIMIT,
): Fact[] {
  const said = facts.filter((fact) => fact.origin === 'user');
  const inferred = facts.filter((fact) => fact.origin !== 'user');

  if (inferred.length <= limit) return [...said, ...inferred];

  const words = wordsOf(userText);

  const ranked = inferred
    .map((fact) => ({ fact, score: score(fact, words) }))
    .sort((a, b) => b.score - a.score || b.fact.updatedAt.localeCompare(a.fact.updatedAt));

  /**
   * Когда вопрос ни с чем не совпал, берём свежие.
   *
   * Пустой блок памяти хуже неточного: агент, у которого совсем ничего нет,
   * ведёт себя как в первый день знакомства, а недавно записанное чаще всего
   * и есть то, что сейчас важно.
   */
  const relevant = ranked.filter((entry) => entry.score >= MIN_SCORE);
  const chosen = (relevant.length > 0 ? relevant : ranked).slice(0, limit);

  return [...said, ...chosen.map((entry) => entry.fact)];
}

/**
 * Насколько факт относится к вопросу.
 *
 * Совпадение по ключу весит больше, чем по значению: ключ — это то, чем факт
 * назвали, а значение может случайно содержать частое слово.
 */
function score(fact: Fact, words: Set<string>): number {
  if (words.size === 0) return 0;

  let total = 0;
  for (const word of wordsOf(fact.key)) if (words.has(word)) total += 2;
  for (const word of wordsOf(fact.value)) if (words.has(word)) total += 1;
  return total;
}

/**
 * Слова строки в сравнимом виде.
 *
 * Ё сворачивается в е — иначе «ещё» и «еще» окажутся разными словами, и факт
 * найдётся или не найдётся в зависимости от раскладки, которой человек набирал.
 *
 * От слова берутся первые четыре буквы. Это не стеммер, а его грубая замена, и
 * нужна она из-за русских окончаний: «язык», «языке», «языком» — одно слово,
 * а при точном сравнении три разных, и факт про рабочий язык не нашёлся бы по
 * вопросу «на каком языке писать».
 *
 * Расплата — случайные совпадения вроде «молоко» и «молодой». Для отбора
 * фактов это дёшево: лишний факт в промпте стоит десяток токенов, а
 * ненайденный нужный — неверный ответ.
 */
function wordsOf(text: string): Set<string> {
  const stems = text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[^\p{L}\p{N}]+/u)
    .filter((word) => word.length >= MIN_WORD)
    .map((word) => word.slice(0, STEM));

  return new Set(stems);
}
