import { describe, expect, it } from 'vitest';
import { policy } from '../src/main/csp.js';

/**
 * Политика решала судьбу целой возможности: с зашитым 127.0.0.1 подключение к
 * своему серверу не работало вовсе, а выглядело это как «проверка прошла,
 * подключиться не удалось» — с уже сгоревшим одноразовым кодом.
 */
describe('политика безопасности', () => {
  it('пускает сокет и вложения того ядра, к которому подключены', () => {
    const result = policy('http://192.168.1.80:8787');

    expect(result).toContain('ws://192.168.1.80:8787');
    // Вложения рендерер показывает прямой ссылкой на /v1/blobs — без этого
    // разговор открывался бы, а картинки в нём молча не грузились.
    expect(result).toMatch(/img-src[^;]*http:\/\/192\.168\.1\.80:8787/);
  });

  it('не пускает никого больше', () => {
    const result = policy('http://192.168.1.80:8787');

    // Картинка по чужой ссылке из ответа модели — готовый маячок: сообщит
    // отправителю, что текст прочитали, вместе с IP.
    expect(result).not.toContain('img-src *');
    expect(result).not.toMatch(/img-src[^;]*\bhttps?:(?![/])/);
    expect(result).toContain("default-src 'self'");
  });

  it('спросить про новую версию можно, унести переписку — нет', () => {
    const result = policy('http://192.168.1.80:8787');

    expect(result).toMatch(/connect-src[^;]*https:\/\/api\.github\.com/);
    // Разрешение касается только запросов: картинку оттуда страница не
    // покажет, а значит и маячком она не станет.
    expect(result).not.toMatch(/img-src[^;]*github/);
  });

  it('своё ядро остаётся разрешённым всегда', () => {
    // К нему возвращаются кнопкой «использовать ядро на этом компьютере», и
    // порт у него каждый раз другой.
    for (const url of [null, 'http://10.0.0.5:8787']) {
      expect(policy(url)).toContain('http://127.0.0.1:*');
    }
  });

  it('мусор вместо адреса не ломает политику целиком', () => {
    // Настройку правят руками, и опечатка не должна оставлять окно без
    // политики вовсе — это было бы хуже, чем неработающее подключение.
    const result = policy('не адрес');

    expect(result).toContain("default-src 'self'");
    expect(result).toContain('http://127.0.0.1:*');
  });
});
