/**
 * Политика безопасности содержимого — под то ядро, к которому подключены.
 *
 * Раньше она была статической строкой в index.html и разрешала только
 * `127.0.0.1`. Пока ядро своё, это работало; при подключении к чужому ядру
 * получалась ловушка: обмен кода на токен идёт из главного процесса, где CSP
 * не действует, поэтому он проходил и **сжигал одноразовый код**, а сокет
 * открывал уже рендерер — и упирался в политику. Снаружи это выглядело как
 * «проверка адреса прошла, подключиться не удалось», и второй раз тот же код
 * уже не принимался.
 *
 * Расширить политику до «любой адрес» нельзя: `img-src` намеренно не пускает
 * чужие узлы (картинка по ссылке из ответа модели — готовый маячок), а
 * вложения ядра рендерер показывает прямыми ссылками на `/v1/blobs`. Значит,
 * адрес ядра должен попасть в политику — и никакой другой.
 */
export function policy(coreUrl: string | null): string {
  const core = origin(coreUrl);
  /**
   * Своё ядро на 127.0.0.1 остаётся всегда: к нему приложение возвращается по
   * кнопке «использовать ядро на этом компьютере», и порт у него разный.
   *
   * Список выпусков — единственный чужой адрес, разрешённый окну.
   *
   * Приложение раздаётся файлом, и узнать о новой версии человеку неоткуда.
   * Пускаем именно этот адрес, а не «любой https»: разница между «можно
   * спросить у GitHub про версию» и «можно унести переписку куда угодно»
   * — как раз в этой строчке.
   */
  const http = [
    "'self'",
    'http://127.0.0.1:*',
    'https://api.github.com',
    ...(core ? [core.http] : []),
  ];
  const socket = ['ws://127.0.0.1:*', ...(core ? [core.ws] : [])];

  return [
    "default-src 'self'",
    `connect-src ${[...http, ...socket].join(' ')}`,
    `img-src ${["'self'", 'data:', 'blob:', 'http://127.0.0.1:*', ...(core ? [core.http] : [])].join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "font-src 'self' data:",
  ].join('; ');
}

/**
 * Из адреса ядра — источник для политики: схема, узел, порт. Путь и токен в
 * CSP не участвуют, а мусор в настройке не должен ломать всю политику.
 */
function origin(coreUrl: string | null): { http: string; ws: string } | null {
  if (!coreUrl) return null;
  try {
    const url = new URL(coreUrl);
    const http = url.origin;
    return { http, ws: http.replace(/^http/, 'ws') };
  } catch {
    return null;
  }
}
